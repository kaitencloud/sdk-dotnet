def method_name(opid, resource, path):
    if opid in METHOD_NAMES:
        return METHOD_NAMES[opid]
    entity = ENTITIES[resource]
    name = pascal(opid)
    name = name.replace(entity + 'Integration', 'Integration')
    for verb in ['List', 'Get', 'Create', 'Update', 'Delete', 'Publish', 'Archive', 'Unarchive']:
        if name.startswith(verb) and name[len(verb):] in {entity, entity + 's'}:
            return verb
    return name


